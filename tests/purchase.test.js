const test = require('node:test');
const assert = require('node:assert/strict');
const db = require('../miniprogram/mock/data');
let role = 'boss';
global.wx = { getStorageSync: () => role };
const mock = require('../miniprogram/mock');
const call = (url, method = 'GET', data = {}) => mock.handle({ url, method, data });
let serial = 0;
function imei() {
  const p = '97000000' + String(++serial).padStart(6, '0');
  let sum = 0; [...p].forEach((v, i) => { let n = Number(v) * (i % 2 ? 2 : 1); sum += n > 9 ? n - 9 : n; });
  return p + (10 - sum % 10) % 10;
}
test('采购 mock 与真实契约一致：逐台验收原子性、字段裁剪、幂等及异常复验', async () => {
  let r = await call('/suppliers', 'POST', { name: '采购测试供应商', active: true }); assert.equal(r.code, 0);
  const supplier = r.data, template = db.templates.find(t => t.id === 't_phone');
  r = await call('/purchase-orders', 'POST', { supplierId: supplier.id, expectedAt: '2026-11-20', freight: '12.34', lines: [{ modelId: 'm_17pm', quantity: 3, unitCost: '1000.12' }] });
  assert.equal(r.code, 0); const po = r.data; assert.equal(po.amount, 3012.70);
  r = await call('/purchase-orders/' + po.id + '/shipments', 'POST', { carrier: 'SF', trackingNo: 'MOCKVERIFY001' });
  assert.equal(r.code, 0); const shipment = r.data;
  r = await call('/purchase-orders', 'GET', { keyword: 'MOCKVERIFY001', supplierId: supplier.id });
  assert.equal(r.data.total, 1); assert.equal(r.data.summary.inTransitQty, 3);
  await call('/shipments/' + shipment.id + '/receive', 'POST', { reason: '测试签收' });
  role = 'warehouse';
  r = await call('/purchase-orders/' + po.id);
  assert.equal(r.data.amount, undefined); assert.equal(r.data.lines[0].unitCost, undefined); assert.equal(r.data.supplierId, undefined);
  assert.equal((await call('/purchase-orders', 'GET', { supplierId: supplier.id })).code, 403);
  const proof = mock.registerFile({ filePath: 'fixture-receipt.png', scope: 'internal' });
  const values = Object.fromEntries(template.fields.map(f => [f.key, f.type === 'image' ? [proof] : f.type === 'select' ? f.options[0] : f.type === 'number' ? 90 : '验证参数']));
  const lineId = po.lines[0].id;
  const makePass = () => ({ modelId: 'm_17pm', lineId, templateVersion: template.version, imei1: imei(), result: 'pass', cost: '0.01', attributes: { ...values }, retail: '1300', wholesale: '1200', agentBase: '1200', receiptImages: [proof] });
  const first = makePass(), second = makePass(), failed = { lineId, imei1: imei(), result: 'fail', remark: '合成测试机况异常', receiptImages: [proof] };
  const before = db.units.length, audit = db.auditLogs.length;
  r = await call('/purchase-orders/' + po.id + '/acceptance', 'POST', { requestKey: 'bad', declaredCount: 3, items: [first, { ...second, retail: '1.001' }, failed] });
  assert.equal(r.code, 400); assert.equal(db.units.length, before); assert.equal(db.auditLogs.length, audit);
  assert.equal((await call('/purchase-orders/' + po.id)).data.lines[0].received, 0);
  const payload = { requestKey: 'good', declaredCount: 3, items: [first, second, failed] };
  r = await call('/purchase-orders/' + po.id + '/acceptance', 'POST', payload);
  assert.equal(r.code, 0, r.message); assert.equal(r.data.accepted, 2); assert.equal(new Set(r.data.unitIds).size, 2);
  assert.equal(db.units.find(u => u.id === r.data.unitIds[0]).cost, 1000.12);
  assert.equal(db.units.find(u => u.id === r.data.unitIds[0]).supplier, supplier.name);
  assert.deepEqual((await call('/purchase-orders/' + po.id + '/acceptance', 'POST', payload)).data, r.data);
  assert.equal(db.units.length, before + 2);
  assert.equal((await call('/inbound/check-imei', 'POST', { imei: failed.imei1 })).data.unique, false);
  const exceptionId = r.data.itemIds[2];
  const detail = (await call('/purchase-orders/' + po.id)).data;
  assert.equal(detail.exceptions[0].receiptImages, undefined);
  assert.equal((await call('/acceptances/' + exceptionId + '/resolve', 'POST', { action: 'reinspect', reason: '错误串码', unit: makePass() })).code, 400);
  r = await call('/acceptances/' + exceptionId + '/resolve', 'POST', { action: 'reinspect', reason: '合成复验通过', unit: { ...makePass(), imei1: failed.imei1 } });
  assert.equal(r.code, 0, r.message);
  const done = (await call('/purchase-orders/' + po.id)).data;
  assert.equal(done.status, 'completed'); assert.equal(done.lines[0].received, 3); assert.equal(done.lines[0].accepted, 3);
  assert.equal((await call('/acceptances/' + exceptionId + '/resolve', 'POST', { action: 'return', reason: '重复处理' })).code, 409);
  role = 'customer'; assert.equal((await call('/purchase-orders/' + po.id)).code, 403);
});
