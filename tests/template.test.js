const test = require('node:test');
const assert = require('node:assert/strict');
const { validateFields, initialValues, validateValues } = require('../miniprogram/utils/template');
const db = require('../miniprogram/mock/data');
let role = 'boss';
global.wx = { getStorageSync: () => role };
const mock = require('../miniprogram/mock');
const call = (url, method = 'GET', data = {}) => mock.handle({ url, method, data });
const copy = x => JSON.parse(JSON.stringify(x));
test('字段规则与入库值校验', () => {
  const fields = copy(db.templates[0].fields);
  assert.equal(validateFields(fields), '');
  assert.match(validateFields([{ ...fields[0], key: 'constructor' }]), /保留/);
  assert.equal(validateFields([{ ...fields[0], type: 'text', default: '测试' }]), '');
  assert.match(validateFields([...fields, fields[0]]), /重复/);
  assert.match(validateFields([null]), /格式/);
  assert.match(validateFields([{ ...fields[0], type: 'number', default: false }]), /数字/);
  assert.match(validateFields([{ ...fields[0], default: '不存在' }]), /默认值/);
  assert.match(validateFields([{ ...fields[0], options: ['重复', '重复'] }]), /选项/);
  assert.match(validateFields([{ ...fields[0], key: 'supplier' }]), /内部/);
  const bool = { key: 'green', label: '全绿', type: 'boolean', required: true, filterable: false, visibility: ['customer'], default: false };
  assert.equal(validateFields([bool]), '');
  assert.equal(validateValues([bool], initialValues([bool])), '');
  assert.match(validateValues(fields, {}), /版本型号/);
  assert.match(validateValues([{ ...fields[0], type: 'number' }], { version: 'abc' }), /数字/);
});
test('发布、权限、冲突、快照、列表筛选与字段裁剪', async () => {
  for (const r of ['customer', 'peer', 'agent', 'sales']) {
    role = r;
    assert.equal((await call('/templates/t_phone')).code, 403);
    assert.equal((await call('/models/tree')).code, r === 'sales' ? 0 : 403);
  }
  role = 'warehouse';
  assert.equal((await call('/models/tree')).code, 0);
  assert.equal((await call('/templates/t_phone')).code, 0);
  assert.equal((await call('/templates')).code, 403);
  const original = (await call('/templates/t_phone')).data;
  assert.equal((await call('/templates/t_phone/versions', 'POST', { baseVersion: original.version, fields: original.fields })).code, 403);
  role = 'boss';
  assert.equal((await call('/templates/no-such')).code, 404);
  assert.equal((await call('/templates', 'GET', { category: 'tablet' })).data.total, 0);
  const fields = copy(original.fields);
  fields[0].default = fields[0].options[0];
  let res = await call('/templates/t_phone/versions', 'POST', { baseVersion: original.version, fields });
  assert.equal(res.code, 0);
  assert.equal(res.data.version, original.version + 1);
  fields[0].label = '外部引用修改';
  assert.notEqual((await call('/templates/t_phone')).data.fields[0].label, fields[0].label);
  assert.equal((await call('/templates/t_phone/versions', 'POST', { baseVersion: original.version, fields })).code, 409);
  const template = (await call('/templates/t_phone')).data;
  const attributes = {};
  template.fields.forEach(f => { attributes[f.key] = f.type === 'select' ? f.options[0] : f.type === 'number' ? 96 : f.type === 'image' ? [{ fileId: 'receipt-internal', url: 'internal-receipt' }] : '内部供应商'; });
  const payload = { modelId: 'm_17pm', templateVersion: template.version, attributes, imei1: '490154203237518', cost: 6200, retail: 7200, wholesale: 6800, agentBase: 6800, internalNote: '内部备注', publicImages: [{ url: 'public-device' }], flags: { showInShop: true, sharePeer: true } };
  assert.equal((await call('/inbound/units', 'POST', { ...payload, attributes: {} })).code, 400);
  assert.equal((await call('/inbound/units', 'POST', { ...payload, templateVersion: 0 })).code, 409);
  assert.equal((await call('/inbound/units', 'POST', { ...payload, cost: -1 })).code, 400);
  res = await call('/inbound/units', 'POST', payload);
  assert.equal(res.code, 0);
  const unit = db.units.find(u => u.id === res.data.id);
  assert.equal(unit.templateSnapshot.version, template.version);
  assert.equal((await call('/inbound/units', 'POST', payload)).code, 400);
  const updated = copy(template.fields); updated[0].label = '新版本型号';
  assert.equal((await call('/templates/t_phone/versions', 'POST', { baseVersion: template.version, fields: updated })).code, 0);
  assert.equal(unit.templateSnapshot.fields[0].label, template.fields[0].label);
  assert.equal(unit.templateSnapshot.version, template.version);
  const history = (await call('/templates/t_phone/versions', 'GET', { pageSize: 1 })).data;
  assert.equal(history.list.length, 1); assert.equal(history.total, 3);
  for (const r of ['customer', 'peer', 'agent']) {
    role = r;
    const product = (await call(`/shop/units/${unit.id}`)).data;
    for (const key of ['cost', 'supplier', 'internalNote', 'imei1', 'attributes', 'templateSnapshot', 'receipt']) assert.equal(product[key], undefined);
    assert.equal(product.priceType, r === 'peer' ? 'wholesale' : 'retail');
    assert.notEqual(product.imeiMasked, payload.imei1);
    assert.ok(product.publicFields.some(f => f.key === 'battery'));
    assert.ok(product.publicFields.every(f => !['supplier', 'receipt', 'internalNote'].includes(f.key)));
    assert.equal(product.publicFields.some(f => f.key === 'peerGrade'), r === 'peer');
  }
  role = 'customer';
  unit.flags.showInShop = false;
  assert.equal((await call(`/shop/units/${unit.id}`)).code, 404);
  assert.ok((await call('/shop/units')).data.list.every(u => u.id !== unit.id));
  role = 'peer';
  unit.flags.sharePeer = false;
  assert.equal((await call(`/shop/units/${unit.id}`)).code, 404);
  assert.ok((await call('/shop/units')).data.list.every(u => u.id !== unit.id));
  unit.flags.showInShop = true; unit.flags.sharePeer = true; unit.status = 'repairing';
  assert.equal((await call(`/shop/units/${unit.id}`)).code, 404);
  unit.status = 'in_stock';
  role = 'sales';
  const staff = (await call(`/units/${unit.id}`)).data;
  for (const key of ['cost', 'supplier', 'internalNote', 'attributes', 'templateSnapshot', 'imei2', 'agentBase']) assert.equal(staff[key], undefined);
  assert.ok(staff.imeiMasked.includes('****'));
  role = 'customer'; assert.equal((await call(`/units/${unit.id}`)).code, 403);
  assert.ok(db.auditLogs.some(a => a.action === '发布模板版本'));
});

test('mock 文件元信息与内部凭证访问隔离', async () => {
  role = 'boss';
  const file = mock.registerFile({ filePath: '/fixture/internal-receipt.png', scope: 'internal' });
  const second = mock.registerFile({ filePath: '/fixture/public-device.png', scope: 'public' });
  assert.notEqual(file.fileId, second.fileId);
  assert.equal((await call(`/files/${file.fileId}`)).code, 0);
  role = 'customer';
  assert.equal((await call(`/files/${file.fileId}`)).code, 403);
  assert.equal((await call(`/files/${second.fileId}`)).code, 0);
  assert.throws(() => mock.registerFile({ filePath: '/fixture/upload.png', scope: 'public' }), /无权限/);
});
